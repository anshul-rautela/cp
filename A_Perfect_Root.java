import java.util.Scanner;

public class A_Perfect_Root {

    public static void main(String[] args) {
        Scanner scn = new Scanner(System.in);
        int t = scn.nextInt();
        while (t--!=0) {
            scn.nextLine();
            int n = scn.nextInt();            
        
            for(int i =1;i<=n;i++){
                System.out.print(i+" ");
                // System.out.printl);
            }
            System.out.println();
        }
    }
}